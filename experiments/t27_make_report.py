"""T27: render reports/remote/RESULTS.md from the sweep/baseline jsonls.

Idempotent — regenerate any time; the tables reflect whatever cells exist.
This is the human-readable face of the matrix; the jsonls stay the source of
truth. Protocol stamps are checked: rows not matching the frozen headline
protocol are listed separately rather than silently mixed in.
"""
import json
import os
from collections import defaultdict

RR = "../reports/remote"
FLOOR = {"leak": 0.3950, "util": 0.5961}   # retain95, rouge_score protocol
PROTO = {"template": "llama3", "rouge_impl": "rouge_score", "max_new": 64}


def rows_of(path):
    if not os.path.exists(path):
        return []
    return [json.loads(l) for l in open(path)]


def protocol_ok(r):
    return all(r.get(k) == v for k, v in PROTO.items())


def agg(rows, cell_key):
    groups = defaultdict(list)
    for r in rows:
        groups[cell_key(r)].append(r)
    out = []
    for k, rs in sorted(groups.items()):
        def ms(key):
            vs = [(x.get("fq_p_vs_retain95") or 0.0) if key == "fq" else x[key]
                  for x in rs]
            return sum(vs) / len(vs), (max(vs) - min(vs)) / 2
        fq, fqr = ms("fq")
        lk, lkr = ms("forget_rouge")
        ut, utr = ms("model_utility")
        out.append((k, len(rs), fq, fqr, lk, lkr, ut, utr))
    return out


def table(agg_rows):
    lines = ["| config | seeds | forget quality (KS p) | leakage (gen R-L) | model utility |",
             "|---|---|---|---|---|"]
    for k, n, fq, fqr, lk, lkr, ut, utr in agg_rows:
        adm = " **✓**" if fq > 0.05 else ""
        lines.append(f"| {k} | {n} | {fq:.4f} ± {fqr:.4f}{adm} "
                     f"| {lk:.4f} ± {lkr:.4f} | {ut:.4f} ± {utr:.4f} |")
    return "\n".join(lines)


def main():
    ours = [r for r in rows_of(f"{RR}/t20_forget05_sweep.jsonl")]
    base = [r for r in rows_of(f"{RR}/t23_baselines_forget05.jsonl")]
    bad = [r for r in ours + base if not protocol_ok(r)]
    ours = [r for r in ours if protocol_ok(r)]
    base = [r for r in base if protocol_ok(r)]

    ours_agg = agg(ours, lambda r: r["cell"]
                   .replace("t20_forget05_", "ours ").rsplit("_", 1)[0])
    base_agg = agg(base, lambda r: r["cell"]
                   .replace("t23_forget05_", "").rsplit("_", 1)[0])

    doc = f"""# TOFU forget05 matrix — Llama-3.2-1B (living results)

Auto-generated by `experiments/t27_make_report.py`; jsonls in this directory
are the source of truth. Protocol: llama3 chat template, greedy 64 new tokens,
`rouge_score` R-L recall, FQ = KS vs the published retain95 truth-ratio log.
Prereg frozen at `96f8fec`, amendments 1-3. Mean ± half-range over seeds.

**Reference points:** retain95 (never-knew): leakage {FLOOR['leak']}, utility
{FLOOR['util']}. Published full-model FQ on forget05: 1.43e-12.
Admissibility: mean FQ p > 0.05 (marked ✓).

## Ours (margin pin + retain hinge + KL anchor)

steps: all-token 100, min-token 450 (per-scope calibration, amendment 3)

{table(ours_agg)}

## Baselines (open-unlearning published configs, effective batch 32)

{table(base_agg) if base_agg else "*(pending — runs chained behind the grid)*"}

## Notes

- FQ p-values are heavily seed-dependent (observed 4 orders of magnitude across
  seeds at fixed config); single-seed FQ numbers are not meaningful.
- Leakage is comparable ONLY within this protocol. Absolute values are not
  comparable to published TOFU ROUGE (decode protocol sensitivity ~15% rel.).
- An admissible model should leak ≈ the floor, not below it: the reference
  itself leaks {FLOOR['leak']}. Leakage far below floor indicates
  over-suppression, which FQ punishes.
"""
    if bad:
        doc += ("\n## Excluded rows (protocol mismatch)\n\n" +
                "\n".join(f"- {r.get('cell', r.get('tag'))}: " +
                          ", ".join(f"{k}={r.get(k)}" for k in PROTO)
                          for r in bad) + "\n")
    open(f"{RR}/RESULTS.md", "w").write(doc)
    print(f"wrote {RR}/RESULTS.md  (ours cells: {len(ours)}, baseline cells: "
          f"{len(base)}, excluded: {len(bad)})")


if __name__ == "__main__":
    main()
